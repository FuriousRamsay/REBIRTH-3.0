from pathlib import Path
import hashlib
import unittest
ROOT=Path(__file__).resolve().parents[1]
class ManifestTests(unittest.TestCase):
    def test_file_hash_manifest_when_generated(self):
        manifest=ROOT/'FILES.sha256'
        if not manifest.exists(): self.skipTest('manifest generated by release packaging stage')
        for line in manifest.read_text().splitlines():
            if not line.strip(): continue
            digest,relative=line.split('  ',1)
            item=ROOT/relative
            self.assertTrue(item.is_file(),relative)
            self.assertEqual(hashlib.sha256(item.read_bytes()).hexdigest(),digest,relative)
